# reverse()

days_of_week = ["Mon", "Tue", "Wed", "Thru", "Fri", "Sat", "Sun"]
print(days_of_week)

days_of_week.reverse()
print(days_of_week)

# sort

nums = [4, 9, 0, 1, 2, 8]
print(nums)
# sort in Ascending order by default
nums.sort()
print(nums)

# sort in descending order
nums.sort(reverse=True)
print(f"Sorted in Descending order{nums}")

# Count():
number = [0,1,3,4,1,0,5,0,0,3,0]
print(number.count(0))

# Membership Operatin in list

